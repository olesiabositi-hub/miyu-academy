export function t(locale: Locale, key: UiKey, vars?: Record<string, string | number>): string {
  const raw: string = locale === "ru" ? ru[key] : en[key];
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}
